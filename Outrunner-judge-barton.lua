-- Вернет описание содержимого сценария для генератора - ОК
function getTemplateContents(races, scenarioSize, parameters)
	local contents = {}
		
	if parameters then
		-- Режим
		if parameters[1] then
			gmode = parameters[1]
			if parameters[1] == 1 then
				contents.startingGold = 700
				contents.startingNativeMana = 200
				contents.roads = 35
				contents.forest = 30
			elseif parameters[1] == 2 then
				contents.startingGold = 1100
				contents.startingNativeMana = 400
				contents.roads = 30
				contents.forest = 30
			end
		end		
		-- Модификация
		if parameters[2] then
			if parameters[2] == 2 then
				kotovasia = 1
			elseif parameters[2] == 3 then
				playmobs = 1
			elseif parameters[2] == 4 then
				accuracy10 = 1
			end
		end
		-- Сила Нейтралы
		if parameters[3] then
			kef = parameters[3] / 100 * 0.92 -- 0.92 - старое расчётное значение
		end		
	end

	contents.customSubraces = customSubraces()
	contents.scenarioVariables = getScenarioVariables()
	contents.zones = getZones(races)
	contents.connections = getZoneConnections(races)

	return contents
end

