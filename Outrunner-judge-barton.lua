function getBuildings(race)
    local buildings = {}

    if kotovasia == 1 then
        for _, raceData in pairs(BUILDINGS) do
            for _, categoryVariants in pairs(raceData) do
                local chosen = categoryVariants[math.random(#categoryVariants)]
                for _, id in pairs(chosen) do
                    table.insert(buildings, id)
                end
            end
        end
    end

    return buildings
end




function kotovasiaGold(value)
    if kotovasia == 1 then
        return math.floor(value / 2)
    end
    return value
end

function applyKotovasiaMines(mines, isStartZone)
    if kotovasia ~= 1 then
        return mines
    end

    -- если НЕ стартовая зона ? убираем золото
    if not isStartZone then
        mines.gold = nil
    end

    return mines
end
